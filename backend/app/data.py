def fake_weather(county: str, day: Date) -> Weather:
    seed = zlib.crc32(f"{county}-{day.isoformat()}".encode())
    rain = seed % 101
    temperature = 18 + (seed // 101) % 14
    summary = "rain" if rain >= 60 else "cloudy" if rain >= 30 else "sunny"
    return Weather(summary=summary, rain_probability=rain, temperature_c=temperature)